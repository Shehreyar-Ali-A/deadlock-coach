export function regularShop(a: {class_name: string; type: string; shopable?: boolean; disabled?: boolean; item_tier?: number; cost?: number}) {
  return classes.has(a.class_name) && a.type === "upgrade" && a.shopable === true && !a.disabled &&
    Number.isInteger(a.item_tier) && a.item_tier! >= 1 && a.item_tier! <= 4 && Number.isSafeInteger(a.cost) && a.cost! > 0;
}
